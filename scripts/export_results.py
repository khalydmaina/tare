#!/usr/bin/env python3
"""Write docs/RESULTS.md from measured data only.

- Attack table comes from docs/attack_metrics.json. If it was produced by the
  simulated trader, the section is stamped NOT EVIDENCE.
- Live paper numbers come from the Flight Recorder the live loop writes (TARE_DB,
  default data/tare.db), never from the demo seed (data/demo.db). Sections with
  no data say so instead of guessing.
"""

from __future__ import annotations

import json
import math
import sys
from pathlib import Path

from dotenv import load_dotenv

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
load_dotenv(ROOT / ".env")

from core.config import db_path  # noqa: E402
from recorder.db import FlightRecorder  # noqa: E402

GATE_DESC = {
    "G0": "unguarded, fixed 1% risk",
    "G1": "calibration + hard limits + Kelly",
    "G2A": "G1 + anomaly layer",
    "G2": "G2A + M2 ablation (text can lower confidence, never raise it)",
}


def fmt(x, pct=False):
    if x is None:
        return "n/a"
    return f"{100 * x:.0f}%" if pct else f"{x}"


def attack_section(lines: list[str]) -> None:
    path = ROOT / "docs" / "attack_metrics.json"
    if not path.exists():
        lines += ["_No attack run yet: `python scripts/run_attacks.py --llm real ...`_", ""]
        return
    data = json.loads(path.read_text())
    meta, summary = data.get("meta", {}), data.get("summary", [])
    gates = meta.get("gates", ["G0", "G1", "G2A", "G2"])
    if meta.get("trader") == "sim":
        lines += ["> **SIMULATED TRADER. NOT EVIDENCE.** Plumbing check only. "
                  "Re-run with `--llm real` before submitting.", ""]
    lines += [
        f"- Trader: `{meta.get('trader')}`",
        f"- Scenarios: `{meta.get('scenario_source')}`; calibration on the first "
        f"{meta.get('cal_scenarios')} (walk-forward, {meta.get('cal_takes')} takes), "
        f"attacks on the next {meta.get('eval_scenarios')}",
        f"- Generated: {meta.get('generated_at')}",
        "",
        "**HAR** = share of truly losing setups the gate approved. "
        "**ASR** = of the losers the gate blocked on clean data, the share the attack got approved.",
        "",
        "| Attack | " + " | ".join(f"{g} HAR / ASR" for g in gates) + " |",
        "|---|" + "---|" * len(gates),
    ]
    for row in summary:
        cells = [f"{fmt(row.get(f'{g}_HAR'), True)} / {fmt(row.get(f'{g}_ASR'), True)}" for g in gates]
        lines.append(f"| {row['attack']} | " + " | ".join(cells) + " |")
    clean = next((r for r in summary if r["attack"] == "clean"), None)
    if clean:
        lines += ["", "Cost on clean data (share of winning setups still approved):", ""]
        for g in gates:
            lines.append(f"- {g}: {fmt(clean.get(f'{g}_win_retention'), True)} "
                         f"(P&L {clean.get(f'{g}_pnl_pct')}% of equity, non-compounded)")
    lines += ["", "Gates: " + "; ".join(f"**{g}** {GATE_DESC.get(g, '')}" for g in gates), ""]


def live_section(lines: list[str]) -> None:
    db = db_path()
    shown = db.relative_to(ROOT) if db.is_relative_to(ROOT) else db.name
    if not db.exists():
        lines += [f"_No live paper data yet (`{shown}` not found). "
                  "Start `python scripts/run_live.py` on the VPS._", ""]
        return
    rec = FlightRecorder(db)
    status = rec.get_status()
    lines += [f"Bot status: `{status.get('status')}` ({status.get('note') or 'no note'}), "
              f"updated {status.get('updated_at')}", ""]
    for book, ref_type in (("guarded", "real"), ("shadow", "shadow")):
        outcomes = rec.fetch_outcomes(ref_type)
        wins = sum(1 for o in outcomes if o["result"] == "win")
        trades = (f"{len(outcomes)} closed trades, win rate {100 * wins / len(outcomes):.0f}%"
                  if outcomes else "no closed trades yet")
        eq = [e["equity"] for e in rec.fetch_equity(book)]
        if len(eq) < 2:
            lines.append(f"- {book}: not enough equity marks yet; {trades}")
            continue
        peak, mdd = eq[0], 0.0
        for v in eq:
            peak = max(peak, v)
            mdd = max(mdd, (peak - v) / peak if peak else 0)
        rets = [(b - a) / a for a, b in zip(eq, eq[1:]) if a]
        sd = (sum((r - sum(rets) / len(rets)) ** 2 for r in rets) / len(rets)) ** 0.5 if rets else 0
        # One equity mark per 15m cycle → 96 marks a day
        sharpe = (sum(rets) / len(rets)) / sd * math.sqrt(96 * 365) if sd else 0.0
        lines.append(f"- {book}: {eq[0]:.2f} -> {eq[-1]:.2f} "
                     f"({100 * (eq[-1] / eq[0] - 1):+.2f}%), max DD {100 * mdd:.2f}%, "
                     f"annualised Sharpe {sharpe:.2f} over {len(eq)} marks; {trades}")
    lines.append("")


def main() -> None:
    lines = ["# RESULTS", "", "Generated by `scripts/export_results.py` from measured data only.", "",
             "## Attack evaluation", ""]
    attack_section(lines)
    lines += ["## Live paper (Bitget, guarded vs shadow)", ""]
    live_section(lines)
    out = ROOT / "docs" / "RESULTS.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {out}")


if __name__ == "__main__":
    main()
